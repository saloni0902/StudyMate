// Builds docs/diagrams.html from docs/ARCHITECTURE.md: `npm run docs`.
// The page shows the whole document with every Mermaid diagram drawn, so it
// can be opened straight from the folder in any browser, or printed to PDF
// for the project report. Needs internet the first time (loads marked and
// mermaid from a CDN).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const docs = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../docs');
const markdown = fs.readFileSync(path.join(docs, 'ARCHITECTURE.md'), 'utf8');

const html = `<!doctype html>
<!-- Generated by scripts/build-diagrams.mjs from ARCHITECTURE.md. Edit the .md file, then run: npm run docs -->
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>StudyMate · How it works</title>
<style>
  :root { --brand: #004643; --ink: #001e1d; --body: #2e4442; --muted: #56696a; --line: #d5dcd9; --tint: #e4efeb; --cta: #f9bc60; }
  * { box-sizing: border-box; }
  body { margin: 0; background: #e8e4e6; color: var(--body); font: 16px/1.6 system-ui, -apple-system, "Segoe UI", sans-serif; }
  main { max-width: 980px; margin: 0 auto; padding: 32px 16px 64px; }
  article { background: #fffffe; border: 1px solid var(--line); border-radius: 14px; padding: 32px; }
  h1, h2, h3 { color: var(--ink); line-height: 1.25; }
  h1 { margin-top: 0; }
  h2 { margin-top: 48px; padding-top: 16px; border-top: 1px solid var(--line); }
  a { color: var(--brand); }
  code { background: var(--tint); padding: 1px 5px; border-radius: 4px; font-size: .88em; }
  table { border-collapse: collapse; width: 100%; margin: 16px 0; font-size: 14px; }
  th, td { border: 1px solid var(--line); padding: 6px 10px; text-align: left; vertical-align: top; }
  th { background: var(--tint); color: var(--ink); }
  .mermaid { margin: 20px 0; padding: 16px; border: 1px solid var(--line); border-radius: 10px; background: #fff; overflow-x: auto; text-align: center; }
  .mermaid svg { max-width: 100%; height: auto; }
  hr { border: 0; }
  @media print {
    body { background: #fff; }
    main { padding: 0; max-width: none; }
    article { border: 0; padding: 0; }
    h2 { break-before: page; border: 0; }
    .mermaid { break-inside: avoid; }
  }
</style>
</head>
<body>
<main><article id="doc">Loading…</article></main>
<script type="text/markdown" id="source">
${markdown.replace(/<\/script/gi, '<\\/script')}
</script>
<script type="module">
  import { marked } from 'https://cdn.jsdelivr.net/npm/marked@15.0.7/lib/marked.esm.js';
  import mermaid from 'https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.esm.min.mjs';

  const source = document.getElementById('source').textContent;
  const doc = document.getElementById('doc');
  doc.innerHTML = marked.parse(source);

  // Turn \`\`\`mermaid code blocks into diagrams.
  for (const code of doc.querySelectorAll('pre > code.language-mermaid')) {
    const box = document.createElement('div');
    box.className = 'mermaid';
    box.textContent = code.textContent;
    code.parentElement.replaceWith(box);
  }
  // The diagrams live on this page, so link to it instead of the .html file name.
  doc.querySelectorAll('a[href="docs/diagrams.html"]').forEach((a) => a.removeAttribute('href'));

  mermaid.initialize({
    startOnLoad: false,
    theme: 'base',
    securityLevel: 'strict',
    themeVariables: {
      primaryColor: '#e4efeb', primaryBorderColor: '#004643', primaryTextColor: '#001e1d',
      lineColor: '#56696a', secondaryColor: '#fdf1dc', tertiaryColor: '#f6f4f5',
      actorBkg: '#004643', actorTextColor: '#fffffe', actorBorder: '#004643',
      signalColor: '#2e4442', signalTextColor: '#001e1d', noteBkgColor: '#fdf1dc', noteBorderColor: '#f9bc60',
      // alt/else boxes and step numbers in sequence diagrams
      labelBoxBkgColor: '#004643', labelBoxBorderColor: '#004643', labelTextColor: '#fffffe',
      loopTextColor: '#001e1d', sequenceNumberColor: '#fffffe',
      fontFamily: 'system-ui, -apple-system, Segoe UI, sans-serif',
    },
  });
  await mermaid.run({ querySelector: '.mermaid' });
  document.body.dataset.rendered = 'true';
</script>
</body>
</html>
`;

fs.writeFileSync(path.join(docs, 'diagrams.html'), html);
console.log('Wrote docs/diagrams.html');
